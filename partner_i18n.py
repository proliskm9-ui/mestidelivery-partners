def ui_text(lang: str, key: str, **kwargs) -> str:
    bucket = UI.get(lang) or UI["ru"]
    text = bucket.get(key) or UI["ru"].get(key) or key
    if kwargs:
        try:
            return text.format(**kwargs)
        except (KeyError, ValueError):
            return text
    return text


